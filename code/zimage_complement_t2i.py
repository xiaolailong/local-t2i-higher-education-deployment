#!/usr/bin/env python3
# -*- coding: utf-8 -*-


import argparse
import os
import re
import sys
import time
import random
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Tuple

import pandas as pd
import requests

from comfy_utils import t2i
from config import COMFY_BASE_URL, COMFY_PORT, MODEL_CONFIG


SHEET_NAME = "Z-Image Complementary"
MODEL_NAME = "zimage"
LANGUAGE = "chinese"

ZIMAGE_PARAMS: Dict[str, int] = {
    "width": 768,
    "height": 768,
    "step": 9,
}

COMFY_WORKDIR = "/home/chenll/ComfyUI"
COMFY_START_CMD = ["python", "main.py", "--listen", "0.0.0.0", "--port", "8188"]
COMFY_READY_TIMEOUT_SEC = 180
COMFY_STOP_TIMEOUT_SEC = 30

_rng = random.SystemRandom()


def safe_str(v: Any) -> str:
    if pd.isna(v):
        return ""
    return str(v).strip()


def safe_int(v: Any, default: int = 3) -> int:
    if pd.isna(v):
        return default
    try:
        return int(float(v))
    except Exception:
        return default


def ensure_exists(path: str) -> None:
    if not os.path.exists(path):
        raise FileNotFoundError(f"File does not exist:{path}")


def sanitize_prompt_id(prompt_id: str) -> str:
    """Clean prompt IDs for filenames. Keep letters, numbers, underscores, and hyphens."""
    prompt_id = safe_str(prompt_id)
    prompt_id = re.sub(r"\s+", "_", prompt_id)
    prompt_id = re.sub(r"[^0-9A-Za-z_\-\u4e00-\u9fff]", "_", prompt_id)
    prompt_id = re.sub(r"_+", "_", prompt_id).strip("_")
    if not prompt_id:
        raise ValueError("ID is empty and cannot be used as promptNo for filename generation.")
    return prompt_id


def random_seed() -> int:
    """Use fixed 15-digit random integers, consistent with earlier experiment stages."""
    return _rng.randrange(10**14, 10**15)


def is_comfy_ready() -> bool:
    try:
        resp = requests.get(f"{COMFY_BASE_URL}/system_stats", timeout=3)
        return resp.status_code == 200
    except Exception:
        return False


def is_port_open(host: str = "127.0.0.1", port: int = COMFY_PORT) -> bool:
    import socket
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(1.0)
        return sock.connect_ex((host, port)) == 0


def stop_comfyui() -> None:
    try:
        subprocess.run(
            ["pkill", "-f", r"python main\.py --listen 0\.0\.0\.0 --port 8188"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
    except Exception:
        pass

    start = time.time()
    while time.time() - start < COMFY_STOP_TIMEOUT_SEC:
        if not is_port_open(port=COMFY_PORT):
            return
        time.sleep(1)

    raise RuntimeError("Stopping ComfyUI timed out; port 8188 is still open.")


def start_comfyui() -> None:
    log_path = Path(COMFY_WORKDIR) / "stage4_zimage_comfyui_restart.log"
    log_f = open(log_path, "a", encoding="utf-8")

    subprocess.Popen(
        COMFY_START_CMD,
        cwd=COMFY_WORKDIR,
        stdout=log_f,
        stderr=log_f,
        start_new_session=True,
    )

    start = time.time()
    while time.time() - start < COMFY_READY_TIMEOUT_SEC:
        if is_comfy_ready():
            return
        time.sleep(2)

    raise RuntimeError(f"Starting ComfyUI timed out: not ready within {COMFY_READY_TIMEOUT_SEC}s.")


def restart_comfyui() -> None:
    print("=" * 80)
    print("[COMFYUI] restarting ...")
    stop_comfyui()
    start_comfyui()
    print("[COMFYUI] ready")
    print("=" * 80)


def target_image_name(prompt_no: str, width: int, height: int, step: int, seed_no: int) -> str:
    return f"c_{MODEL_NAME}_{prompt_no}_{LANGUAGE}_{width}-{height}_step{step}_{seed_no}.png"


def target_txt_name(prompt_no: str, width: int, height: int, step: int, seed_no: int) -> str:
    return f"c_{MODEL_NAME}_{prompt_no}_{LANGUAGE}_{width}-{height}_step{step}_{seed_no}.txt"


def rename_output(src_path: str, target_path: Path, overwrite: bool = False) -> Path:
    """Rename files generated by comfy_utils.t2i according to the Stage 4 naming rule."""
    src = Path(src_path)
    if not src.exists():
        raise FileNotFoundError(f"Generated file does not exist and cannot be renamed:{src}")

    if src.resolve() == target_path.resolve():
        return target_path

    if target_path.exists():
        if overwrite:
            target_path.unlink()
        else:
            raise FileExistsError(f"Target file already exists:{target_path}.Use --overwrite if you want to overwrite..")

    src.rename(target_path)
    return target_path


Task = Tuple[str, str, int]


def build_prompt_tasks(excel_path: str) -> List[Task]:
    ensure_exists(excel_path)

    df = pd.read_excel(excel_path, sheet_name=SHEET_NAME)

    required_cols = [
        "ID", "Module", "Prompt_Group", "Source_ID", "Prompt_Version",
        "Content", "Style", "Complexity", "Context",
        "Chinese_Prompt", "Generate_N", "Analysis_Note",
    ]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Worksheet {SHEET_NAME} missing required columns:{missing}")

    tasks: List[Task] = []
    seen_ids = set()

    for row_idx, row in df.iterrows():
        raw_id = safe_str(row["ID"])
        prompt_no = sanitize_prompt_id(raw_id)
        prompt_text = safe_str(row["Chinese_Prompt"])
        generate_n = safe_int(row["Generate_N"], default=3)

        if not prompt_text:
            print(f"[SKIP] row {row_idx + 2} line Chinese_Prompt is empty; skipped.")
            continue

        if generate_n <= 0:
            print(f"[SKIP] ID={prompt_no} Generate_N={generate_n}, skipped.")
            continue

        if prompt_no in seen_ids:
            raise ValueError(
                f"ID duplicate:{prompt_no}.The Stage 4 naming rule uses only ID, so duplicate IDs cause filename conflicts."
            )
        seen_ids.add(prompt_no)

        tasks.append((prompt_no, prompt_text, generate_n))

    if not tasks:
        raise ValueError(f"Worksheet {SHEET_NAME} contains no executable tasks.")

    return tasks


def get_first_task(tasks: List[Task]):
    prompt_no, text, _ = tasks[0]
    return prompt_no, text


def warm_once(workflow: str, tasks: List[Task], output_dir: str) -> None:
    prompt_no, text = get_first_task(tasks)
    w = ZIMAGE_PARAMS["width"]
    h = ZIMAGE_PARAMS["height"]
    step = ZIMAGE_PARAMS["step"]
    seed = random_seed()

    print(f"[WARM] {MODEL_NAME} ...")
    t2i(
        model_name=MODEL_NAME,
        workflow_json_path=workflow,
        prompt_no=prompt_no,
        prompt_text=text,
        language=LANGUAGE,
        width=w,
        height=h,
        step=step,
        seed=seed,
        seed_no=0,
        output_dir=output_dir,
        is_warmup=True,
    )


def run_batch(excel_path: str, output_dir: str, overwrite: bool = False) -> None:
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    tasks = build_prompt_tasks(excel_path)
    workflow = MODEL_CONFIG[MODEL_NAME]["json_path"]

    w = ZIMAGE_PARAMS["width"]
    h = ZIMAGE_PARAMS["height"]
    step = ZIMAGE_PARAMS["step"]

    total = sum(generate_n for _, _, generate_n in tasks)
    done = 0

    restart_comfyui()
    print("=== GREENLIGHT TEST: Z-Image-Turbo ===")
    try:
        warm_once(workflow, tasks, output_dir)
    except Exception as e:
        raise RuntimeError(f"Green-light test failed: {MODEL_NAME} {e}")
    print("=== GREENLIGHT OK ===")

    restart_comfyui()
    warm_once(workflow, tasks, output_dir)

    for prompt_no, prompt_text, generate_n in tasks:
        for seed_no in range(generate_n):
            target_png = Path(output_dir) / target_image_name(prompt_no, w, h, step, seed_no)
            target_txt = Path(output_dir) / target_txt_name(prompt_no, w, h, step, seed_no)

            if target_png.exists() and not overwrite:
                done += 1
                print(f"[{done}/{total}] SKIP existing: {target_png}")
                continue

            seed = random_seed()
            done += 1
            print(
                f"[{done}/{total}] model={MODEL_NAME}, ID={prompt_no}, "
                f"res={w}x{h}, step={step}, seed_no={seed_no}, seed={seed}"
            )

            try:
                img_path, txt_path = t2i(
                    model_name=MODEL_NAME,
                    workflow_json_path=workflow,
                    prompt_no=prompt_no,
                    prompt_text=prompt_text,
                    language=LANGUAGE,
                    width=w,
                    height=h,
                    step=step,
                    seed=seed,
                    seed_no=seed_no,
                    output_dir=output_dir,
                    is_warmup=False,
                )

                final_img = rename_output(img_path, target_png, overwrite=overwrite)
                print(f"    -> image: {final_img}")

                if txt_path and Path(txt_path).exists():
                    final_txt = rename_output(txt_path, target_txt, overwrite=overwrite)
                    print(f"    -> monitor: {final_txt}")
                else:
                    print("    -> monitor: monitor txt file not found")

            except Exception as e:
                print(f"ERROR: ID={prompt_no}, seed_no={seed_no}, {e}", file=sys.stderr)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Stage 4 Z-Image-Turbo batch text-to-image generation script")
    parser.add_argument("excel_path", help="Excel file path; must contain the Z-Image Complementary worksheet")
    parser.add_argument("output_dir", help="output directory")
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite target files if they already exist. By default, existing files are skipped.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    run_batch(args.excel_path, args.output_dir, overwrite=args.overwrite)
